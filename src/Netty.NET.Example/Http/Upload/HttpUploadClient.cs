    internal static readonly string BASE_URL = ExampleLauncher.GetProperty("baseUrl", "http://127.0.0.1:8080/");
    internal static readonly string FILE = ExampleLauncher.GetProperty("file", "upload.txt");

    public static async Task Main(string[] args)
    {
        string postSimple, postFile, get;
        if (BASE_URL.EndsWith("/", StringComparison.Ordinal))
        {
            postSimple = BASE_URL + "formpost";
            postFile = BASE_URL + "formpostmultipart";
            get = BASE_URL + "formget";
        }
        else
        {
            postSimple = BASE_URL + "/formpost";
            postFile = BASE_URL + "/formpostmultipart";
            get = BASE_URL + "/formget";
        }

        Uri uriSimple = new Uri(postSimple);
        string scheme = string.IsNullOrEmpty(uriSimple.Scheme)? "http" : uriSimple.Scheme;
        string host = string.IsNullOrEmpty(uriSimple.Host)? "127.0.0.1" : uriSimple.Host;
        int port = uriSimple.IsDefaultPort ? -1 : uriSimple.Port;
        if (port == -1)
        {
            if ("http".Equals(scheme, StringComparison.OrdinalIgnoreCase))
            {
                port = 80;
            }
            else if ("https".Equals(scheme, StringComparison.OrdinalIgnoreCase))
            {
                port = 443;
            }
        }

        if (!"http".Equals(scheme, StringComparison.OrdinalIgnoreCase) && !"https".Equals(scheme, StringComparison.OrdinalIgnoreCase))
        {
            Console.Error.WriteLine("Only HTTP(S) is supported.");
            return;
        }

        bool ssl = "https".Equals(scheme, StringComparison.OrdinalIgnoreCase);
        SslContext sslCtx;
        if (ssl)
        {
            sslCtx = SslContextBuilder.ForClient()
                .TrustManager(InsecureTrustManagerFactory.INSTANCE).Build();
        }
        else
        {
            sslCtx = null;
        }

        Uri uriFile = new Uri(postFile);
        FileInfo file = new FileInfo(FILE);
        if (!file.Exists)
        {
            throw new FileNotFoundException(FILE);
        }

        // Configure the client.
        IEventLoopGroup group = new MultiThreadIoEventLoopGroup(NioIoHandler.NewFactory());

        // setup the factory: here using a mixed memory/disk based on size threshold
        IHttpDataFactory factory = new DefaultHttpDataFactory(DefaultHttpDataFactory.MINSIZE); // Disk if MINSIZE exceed

        DiskFileUpload.deleteOnExitTemporaryFile = true; // should delete file on exit (in normal exit)
        DiskFileUpload.baseDirectory = null; // system temp directory
        DiskAttribute.deleteOnExitTemporaryFile = true; // should delete file on exit (in normal exit)
        DiskAttribute.baseDirectory = null; // system temp directory

        try
        {
            Bootstrap b = new Bootstrap();
            b.Group(group).Channel<NioSocketChannel>().Handler(new HttpUploadClientInitializer(sslCtx));

            // Simple Get form: no factory used (not usable)
            IList<IEntry<string, string>> headers = await FormgetAsync(b, host, port, get, uriSimple);
            if (headers == null)
            {
                factory.CleanAllHttpData();
                return;
            }

            // Simple Post form: factory used for big attributes
            IList<IInterfaceHttpData> bodylist = await FormpostAsync(b, host, port, uriSimple, file, factory, headers);
            if (bodylist == null)
            {
                factory.CleanAllHttpData();
                return;
            }

            // Multipart Post form: factory used
            await FormpostmultipartAsync(b, host, port, uriFile, factory, headers, bodylist);
        }
        finally
        {
            // Shut down executor threads to exit.
            _ = group.ShutdownGracefullyAsync();

            // Really clean all temporary files if they still exist
            factory.CleanAllHttpData();
        }
    }

    /**
     * Standard usage of HTTP API in Netty without file Upload (get is not able to achieve File upload
     * due to limitation on request size).
     *
     * @return the list of headers that will be used in every example after
     **/
    private static async Task<IList<IEntry<string, string>>> FormgetAsync(
            Bootstrap bootstrap, string host, int port, string get, Uri uriSimple)
    {
        // XXX /formget
        // No use of HttpPostRequestEncoder since not a POST
        IChannel channel = await bootstrap.ConnectAsync(host, port);

        // Prepare the HTTP request.
        QueryStringEncoder encoder = new QueryStringEncoder(get);
        // add Form attribute
        encoder.AddParam("getform", "GET");
        encoder.AddParam("info", "first value");
        encoder.AddParam("secondinfo", "secondvalue ���&");
        // not the big one since it is not compatible with GET size
        // encoder.addParam("thirdinfo", textArea);
        encoder.AddParam("thirdinfo", "third value\r\ntest second line\r\n\r\nnew line\r\n");
        encoder.AddParam("Send", "Send");

        Uri uriGet = new Uri(encoder.ToString());
        IHttpRequest request = new DefaultHttpRequest(HttpVersion.HTTP_1_1, HttpMethod.GET, uriGet.AbsoluteUri);
        HttpHeaders headers = request.Headers();
        headers.Set(HttpHeaderNames.HOST, host);
        headers.Set(HttpHeaderNames.CONNECTION, HttpHeaderValues.CLOSE);
        headers.Set(HttpHeaderNames.ACCEPT_ENCODING, HttpHeaderValues.GZIP + "," + HttpHeaderValues.DEFLATE);

        headers.Set(HttpHeaderNames.ACCEPT_CHARSET, "ISO-8859-1,utf-8;q=0.7,*;q=0.7");
        headers.Set(HttpHeaderNames.ACCEPT_LANGUAGE, "fr");
        headers.Set(HttpHeaderNames.REFERER, uriSimple.OriginalString);
        headers.Set(HttpHeaderNames.USER_AGENT, "Netty Simple Http Client side");
        headers.Set(HttpHeaderNames.ACCEPT, "text/html,application/xhtml+xml,application/xml;q=0.9,*/*;q=0.8");

        //connection will not close but needed
        // headers.set("Connection","keep-alive");
        // headers.set("Keep-Alive","300");

        headers.Set(
                HttpHeaderNames.COOKIE, ClientCookieEncoder.STRICT.Encode(
                        new DefaultCookie("my-cookie", "foo"),
                        new DefaultCookie("another-cookie", "bar"))
        );

        // send request
        _ = channel.WriteAsync(request);
        _ = channel.WriteAndFlushAsync(ILastHttpContent.EMPTY_LAST_CONTENT);

        // Wait for the server to close the connection.
        await channel.CloseFuture;

        // convert headers to list
        return headers.Entries();
    }

    /**
     * Standard post without multipart but already support on Factory (memory management)
     *
     * @return the list of HttpData object (attribute and file) to be reused on next post
     */
    private static async Task<IList<IInterfaceHttpData>> FormpostAsync(
            Bootstrap bootstrap,
            string host, int port, Uri uriSimple, FileInfo file, IHttpDataFactory factory,
            IList<IEntry<string, string>> headers)
    {
        // XXX /formpost
        // Start the connection attempt.
        Task<IChannel> future = bootstrap.ConnectAsync(new System.Net.DnsEndPoint(host, port));
        // Wait until the connection attempt succeeds or fails.
        IChannel channel = await future;

        // Prepare the HTTP request.
        IHttpRequest request = new DefaultHttpRequest(HttpVersion.HTTP_1_1, HttpMethod.POST, uriSimple.AbsoluteUri);

        // Use the PostBody encoder
        HttpPostRequestEncoder bodyRequestEncoder =
                new HttpPostRequestEncoder(factory, request, false);  // false => not multipart

        // it is legal to add directly header or cookie into the request until finalize
        foreach (IEntry<string, string> entry in headers)
        {
            request.Headers().Set(entry.GetKey(), entry.GetValue());
        }

        // add Form attribute
        bodyRequestEncoder.AddBodyAttribute("getform", "POST");
        bodyRequestEncoder.AddBodyAttribute("info", "first value");
        bodyRequestEncoder.AddBodyAttribute("secondinfo", "secondvalue ���&");
        bodyRequestEncoder.AddBodyAttribute("thirdinfo", textArea);
        bodyRequestEncoder.AddBodyAttribute("fourthinfo", textAreaLong);
        bodyRequestEncoder.AddBodyFileUpload("myfile", file, "application/x-zip-compressed", false);

        // finalize request
        request = bodyRequestEncoder.FinalizeRequest();

        // Create the bodylist to be reused on the last version with Multipart support
        IList<IInterfaceHttpData> bodylist = bodyRequestEncoder.GetBodyListAttributes();

        // send request
        _ = channel.WriteAsync(request);

        // test if request was chunked and if so, finish the write
        if (bodyRequestEncoder.IsChunked())
        { // could do either request.isChunked()
            // either do it through ChunkedWriteHandler
            _ = channel.WriteAsync(bodyRequestEncoder);
        }
        channel.Flush();

        // Do not clear here since we will reuse the InterfaceHttpData on the next request
        // for the example (limit action on client side). Take this as a broadcast of the same
        // request on both Post actions.
        //
        // On standard program, it is clearly recommended to clean all files after each request
        // bodyRequestEncoder.cleanFiles();

        // Wait for the server to close the connection.
        await channel.CloseFuture;
        return bodylist;
    }

    /**
     * Multipart example
     */
    private static async Task FormpostmultipartAsync(
            Bootstrap bootstrap, string host, int port, Uri uriFile, IHttpDataFactory factory,
            IEnumerable<IEntry<string, string>> headers, IList<IInterfaceHttpData> bodylist)
    {
        // XXX /formpostmultipart
        // Start the connection attempt.
        Task<IChannel> future = bootstrap.ConnectAsync(new System.Net.DnsEndPoint(host, port));
        // Wait until the connection attempt succeeds or fails.
        IChannel channel = await future;

        // Prepare the HTTP request.
        IHttpRequest request = new DefaultHttpRequest(HttpVersion.HTTP_1_1, HttpMethod.POST, uriFile.AbsoluteUri);

        // Use the PostBody encoder
        HttpPostRequestEncoder bodyRequestEncoder =
                new HttpPostRequestEncoder(factory, request, true); // true => multipart

        // it is legal to add directly header or cookie into the request until finalize
        foreach (IEntry<string, string> entry in headers)
        {
            request.Headers().Set(entry.GetKey(), entry.GetValue());
        }

        // add Form attribute from previous request in formpost()
        bodyRequestEncoder.SetBodyHttpDatas(bodylist);

        // finalize request
        bodyRequestEncoder.FinalizeRequest();

        // send request
        _ = channel.WriteAsync(request);

        // test if request was chunked and if so, finish the write
        if (bodyRequestEncoder.IsChunked())
        {
            _ = channel.WriteAsync(bodyRequestEncoder);
        }
        channel.Flush();

        // Now no more use of file representation (and list of HttpData)
        bodyRequestEncoder.CleanFiles();

        // Wait for the server to close the connection.
        await channel.CloseFuture;
    }

