// CLR adaptations:
// - java.net.URI is System.Uri. A Uri is always absolute here (new Uri(string) rejects a relative reference), so
//   getScheme() and getHost() keep the source's fallbacks for a missing (null or empty) value; getPort() is -1 for a URI
//   without an explicit port, which is a Uri whose IsDefaultPort is true. toASCIIString() is AbsoluteUri (the escaped
//   absolute form) and toString() is OriginalString (the string the URI was created from).
// - java.io.File is FileInfo; canRead() has no BCL check short of opening the file, so a missing file throws the
//   source's FileNotFoundException. The namespace segment File of Netty.NET.Example.Http.File hides System.IO.File
//   in this namespace, so only FileInfo is used.
// - main, formget, formpost and formpostmultipart block on connect(...).sync() and closeFuture().sync(); they are
//   Task-returning async methods (the helpers take the Async suffix) that await the Task<IChannel> of ConnectAsync and
//   the channel's CloseFuture (docs/transport-porting.md: sync() is awaiting the Task). SocketUtils.socketAddress(host,
//   port) is a DnsEndPoint: SocketUtils is retired and native endpoints replace its operations
//   (docs/common-porting.md, Native socket operations); System.Net.DnsEndPoint is qualified because System.Net's
//   HttpVersion would make the codec-http HttpVersion ambiguous. channel.write/writeAndFlush return Tasks, discarded as
//   Java discards the futures, and group.shutdownGracefully() is ShutdownGracefullyAsync().
// - HttpRequest/HttpHeaders/InterfaceHttpData/HttpDataFactory are the codec-http types (I-prefixed interfaces), and
//   Map.Entry<String, String> of the headers is IEntry<string, string> (headers.entries() returns IList of it); the
//   deprecated io.netty.handler.codec.http.ClientCookieEncoder shares the simple name, so the cookie package's encoder
//   is named by a using alias. String.equalsIgnoreCase is an OrdinalIgnoreCase comparison and System.err.println is
//   Console.Error.WriteLine. The SSL context is built by the JDK (SslStream) provider: OPENSSL and tcnative are
//   library-not-ported (docs/handler-porting.md). The private static final Strings are static readonly strings.
public sealed class HttpUploadClient
