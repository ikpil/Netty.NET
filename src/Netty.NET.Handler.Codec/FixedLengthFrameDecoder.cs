using System.Collections.Generic;
using Netty.NET.Buffer;
using Netty.NET.Transport.Channels;
using static Netty.NET.Common.Internal.ObjectUtil;

namespace Netty.NET.Handler.Codec;

/**
 * A decoder that splits the received {@link ByteBuf}s by the fixed number
 * of bytes. For example, if you received the following four fragmented packets:
 * <pre>
 * +---+----+------+----+
 * | A | BC | DEFG | HI |
 * +---+----+------+----+
 * </pre>
 * A {@link FixedLengthFrameDecoder}{@code (3)} will decode them into the
 * following three packets with the fixed length:
 * <pre>
 * +-----+-----+-----+
 * | ABC | DEF | GHI |
 * +-----+-----+-----+
 * </pre>
 */
public class FixedLengthFrameDecoder : ByteToMessageDecoder
{
    private readonly int frameLength;

    /**
     * Creates a new instance.
     *
     * @param frameLength the length of the frame
     */
    public FixedLengthFrameDecoder(int frameLength)
    {
        CheckPositive(frameLength, "frameLength");
        this.frameLength = frameLength;
    }

    protected sealed override void Decode(IChannelHandlerContext ctx, ByteBuf @in, IList<object> @out)
    {
        object decoded = Decode(ctx, @in);
        if (decoded != null)
        {
            @out.Add(decoded);
        }
    }

    /**
     * Create a frame out of the {@link ByteBuf} and return it.
     *
     * @param   ctx             the {@link ChannelHandlerContext} which this {@link ByteToMessageDecoder} belongs to
     * @param   in              the {@link ByteBuf} from which to read data
     * @return  frame           the {@link ByteBuf} which represent the frame or {@code null} if no frame could
     *                          be created.
     */
    protected virtual object Decode(
            IChannelHandlerContext ctx, ByteBuf @in)
    {
        if (@in.ReadableBytes < frameLength)
        {
            return null;
        }
        else
        {
            return @in.ReadRetainedSlice(frameLength);
        }
    }
}
